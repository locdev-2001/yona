function dashboardIcon(Glyph: IconComponent): IconComponent {
    // Base UI truyền children vào icon slot; Reicon tự dựng SVG nên bỏ children của slot.
    const Icon = forwardRef<SVGSVGElement, IconProps>(({ className, children, ...props }, ref) => (
        <Glyph {...props} ref={ref} aria-hidden={props['aria-hidden'] ?? (props['aria-label'] ? undefined : true)} className={['admin-icon', className].filter(Boolean).join(' ')} data-icon-set="reicon" />
    ));
    Icon.displayName = Glyph.displayName;
    return Icon;
}

