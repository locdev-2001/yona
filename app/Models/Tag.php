<?php

namespace App\Models;

use App\Models\Concerns\Auditable;
use Modules\Tenancy\Concerns\BelongsToWorkspace;
use App\Models\Concerns\HasOptimisticLock;
use Database\Factories\TagFactory;
use Illuminate\Database\Eloquent\Concerns\HasUuids;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\SoftDeletes;

/**
 * Workspace-scoped tag definition. Deduplicated by slug per workspace
 * (unique constraint workspace_id + slug). TagService generates slug from name.
 *
 * @use HasFactory<TagFactory>
 */
class Tag extends Model
{
    /** @use HasFactory<TagFactory> */
    use Auditable, BelongsToWorkspace, HasFactory, HasOptimisticLock, HasUuids, SoftDeletes;

    // slug and workspace_id are server-controlled — slug generated by TagService.
    protected $fillable = [
        'name',
        'color',
    ];
}
